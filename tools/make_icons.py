"""Regenerate every branding file from the magpie artwork.

    .venv/Scripts/python.exe tools/make_icons.py

1. Builds the SVG masters in assets/ from the source art assets/magpie.svg:
   logo.svg (round desktop logo), logo-square.svg (full-bleed: iOS, Google Play)
   and logo-android-foreground.svg (adaptive-icon foreground, full 108 dp layer).
   assets/tray-icon.svg is drawn by hand and only read.
2. Renders the PNG / ICO / ICNS sets for assets/, assets/msix/ and the Flutter
   platform folders (Android, iOS, macOS, Windows, app/assets).
3. Renders the Google Play icon and feature graphics into dist/playstore/
   (needs the Outfit font installed; skipped with a warning otherwise).

Every platform uses one composition: the beak, head and grade tag sit inside
Android's 66 dp safe circle, so no launcher mask cuts them. Below 32 px the
flat tray drawing is used instead of the detailed bird, which turns to mud.
Needs Playwright's Chromium (as tools/render_icon.py) and Pillow.
"""
import base64
import glob
import io
import os
import pathlib
import shutil

from PIL import Image
from playwright.sync_api import sync_playwright

ROOT = pathlib.Path(__file__).resolve().parent.parent
A = ROOT / "assets"
RES = ROOT / "app/android/app/src/main/res"
PLAY = ROOT / "dist/playstore"
ORANGE = "#ffa23a"

# Bird placement in a 512 canvas spanning 73.44 dp: there the beak, head and tag fit
# a 230 px circle, i.e. Android's 66 dp safe zone (checked under circle/squircle/teardrop masks).
CX, CY, SCALE = 160, 251, 0.97141
# The foreground master spans the whole 108 dp layer, so the same placement is scaled down.
FG_SCALE = 73.44 / 108


def between(s, start, end, include_end=True):
    i = s.index(start)
    j = s.index(end, i)
    return s[i:j + (len(end) if include_end else 0)]


def build_masters():
    src = (A / "magpie.svg").read_text(encoding="utf-8")
    defs = between(src, "<defs>", "</defs>")[len("<defs>"):-len("</defs>")]
    # body, belly, wing, head, grade tag, beak and eye; tail and legs left out
    bird = between(src, '<path d="M 520 560', '<circle cx="206" cy="95" r="3.5" fill="#fff" opacity="0.85"/>')
    bird = bird.replace(between(bird, '<path d="M 340 570', '<g id="grade">', include_end=False), "")

    def master(name, comment, background, clip, scale=SCALE):
        tf = f"translate(256 256) scale({scale:.6f}) translate({-CX} {-CY})"
        (A / name).write_text(f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">
<!-- {comment}
     Generated by tools/make_icons.py from assets/magpie.svg (legs and tail removed); the beak,
     head and grade tag sit inside Android's adaptive-icon safe zone on every platform. -->
<defs>{defs}
<clipPath id="frame">{clip}</clipPath>
</defs>
<g id="background">{background}</g>
<g id="magpie" clip-path="url(#frame)"><g transform="{tf}">
{bird}
</g></g>
</svg>
''', encoding="utf-8")

    master("logo.svg", "Strakalari logo / desktop icon: magpie with the grade tag on a solid orange circle.",
           f'<circle cx="256" cy="256" r="256" fill="{ORANGE}"/>', '<circle cx="256" cy="256" r="256"/>')
    master("logo-square.svg", "Full-bleed square app icon (iOS, Google Play): the platform rounds the corners itself.",
           f'<rect width="512" height="512" fill="{ORANGE}"/>', '<rect width="512" height="512"/>')
    master("logo-android-foreground.svg",
           f"Android adaptive-icon foreground (transparent), the full 108 dp layer; background is {ORANGE} "
           "(ic_launcher_background). The body runs into the 18 dp bleed for launcher effects.",
           "", '<rect width="512" height="512"/>', SCALE * FG_SCALE)


class Renderer:
    def __init__(self, page):
        self.page = page
        self.svg = {k: "data:image/svg+xml;base64," + base64.b64encode((A / f).read_bytes()).decode()
                    for k, f in {"circle": "logo.svg", "square": "logo-square.svg",
                                 "fg": "logo-android-foreground.svg", "tray": "tray-icon.svg"}.items()}

    def render(self, kind, w, h=None, body=1.0):
        """`kind` as a centred square of body*min(w, h) px on a transparent w x h canvas."""
        h = h or w
        s = round(min(w, h) * body)
        self.page.set_viewport_size({"width": w, "height": h})
        self.page.set_content(f"<body style='margin:0;background:transparent'><img src='{self.svg[kind]}' "
                              f"width={s} height={s} style='position:absolute;left:{(w - s) // 2}px;top:{(h - s) // 2}px'></body>")
        self.page.wait_for_timeout(40)
        return Image.open(io.BytesIO(self.page.screenshot(omit_background=True))).convert("RGBA")

    def desktop(self, size, body=1.0):
        """Round logo; the flat tray drawing below 32 px."""
        return self.render("tray" if size * body < 32 else "circle", size, body=body)


def save(im, path):
    path = pathlib.Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    im.save(path)
    return im


def render_icons(r):
    for s in [16, 22, 24, 32, 36, 48, 64, 72, 96, 128, 192, 256, 512, 1080]:
        save(r.desktop(s), A / f"logo-{s}.png")
    save(r.desktop(512), A / "icon.png")
    save(r.desktop(32), A / "favicon.png")
    save(r.desktop(192), A / "android-chrome-192.png")
    save(r.desktop(512), A / "android-chrome-512.png")
    ico = [r.desktop(s) for s in [16, 24, 32, 48, 64, 128, 256]]
    ico[-1].save(A / "icon.ico", format="ICO", sizes=[i.size for i in ico], append_images=ico[:-1])
    mac = 824 / 1024  # Apple's macOS icon grid: artwork body 824 px of a 1024 canvas
    icns = [r.desktop(s, mac) for s in [16, 32, 64, 128, 256, 512, 1024]]
    icns[-1].save(A / "icon.icns", format="ICNS", append_images=icns[:-1])

    # tray (the app bundles the same files)
    save(r.render("tray", 64), A / "tray-icon.png")
    for s in [16, 22, 24, 32, 48]:
        save(r.render("tray", s), A / f"tray-icon-{s}.png")
    tray = [r.render("tray", s) for s in [16, 24, 32, 48]]
    tray[-1].save(A / "tray-icon.ico", format="ICO", sizes=[i.size for i in tray], append_images=tray[:-1])
    for f in ["tray-icon.png", "tray-icon.ico", "logo-256.png"]:
        shutil.copyfile(A / f, ROOT / "app/assets" / f)

    # MSIX: Windows scales Square44x44Logo down to 24-36 px for the taskbar, so it uses the flat drawing
    m = A / "msix"
    save(r.render("tray", 44), m / "Square44x44Logo.png")
    save(r.desktop(50), m / "StoreLogo.png")
    save(r.desktop(150, 0.85), m / "Square150x150Logo.png")
    save(r.desktop(310, 0.85), m / "Square310x310Logo.png")
    save(r.render("circle", 310, 150, 0.85), m / "Wide310x150Logo.png")

    # Flutter platform folders
    shutil.copyfile(A / "icon.ico", ROOT / "app/windows/runner/resources/app_icon.ico")
    for p in glob.glob(str(ROOT / "app/macos/Runner/Assets.xcassets/AppIcon.appiconset/app_icon_*.png")):
        save(r.desktop(Image.open(p).width, mac), p)
    for p in glob.glob(str(ROOT / "app/ios/Runner/Assets.xcassets/AppIcon.appiconset/Icon-App-*.png")):
        w = Image.open(p).width  # iOS wants opaque full-bleed squares and applies its own mask
        sq = r.render("square", w)
        bg = Image.new("RGB", (w, w), ORANGE)
        bg.paste(sq, (0, 0), sq)
        save(bg, p)
    for dpi, s in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
        save(r.render("circle", s), RES / f"mipmap-{dpi}" / "ic_launcher.png")  # pre-8.0 launchers
        save(r.render("fg", s * 108 // 48), RES / f"drawable-{dpi}" / "ic_launcher_foreground.png")


def find_outfit():
    for d in [pathlib.Path(os.environ.get("LOCALAPPDATA", "")) / "Microsoft/Windows/Fonts",
              pathlib.Path(os.environ.get("WINDIR", "C:/Windows")) / "Fonts"]:
        hits = sorted(d.glob("Outfit*.ttf"))
        if hits:
            return hits[0]
    return None


FEATURE_TEXT = {"cs": "Rozvrh, známky, absence a&nbsp;obědy na jednom místě",
                "en": "Timetable, marks, absences and lunches in one place"}


def feature_html(font, bird, tagline):
    return f"""<html><head><style>
@font-face {{ font-family: Outfit; src: url(data:font/ttf;base64,{font}); font-weight: 100 900; }}
* {{ margin: 0; padding: 0; }}
body {{ width: 1024px; height: 500px; overflow: hidden; position: relative; font-family: Outfit;
  background: radial-gradient(circle at 76% 42%, #ffc874 0, {ORANGE} 46%, #f48a26 100%); }}
.grid {{ position: absolute; inset: 0;
  background-image: linear-gradient(rgba(255,255,255,.11) 1.5px, transparent 1.5px),
                    linear-gradient(90deg, rgba(255,255,255,.11) 1.5px, transparent 1.5px);
  background-size: 32px 32px; background-position: -1px 6px; }}
.bird {{ position: absolute; right: -6px; top: 2px; width: 512px; height: 512px; }}
.text {{ position: absolute; left: 68px; top: 0; bottom: 0; width: 430px; display: flex; flex-direction: column; justify-content: center; }}
h1 {{ font-weight: 800; font-size: 96px; letter-spacing: -2px; color: #1c1813; line-height: 1; }}
svg.pen {{ display: block; margin: 6px 0 22px 4px; }}
p {{ font-weight: 500; font-size: 31px; line-height: 1.25; color: #3d2610; }}
</style></head><body><div class="grid"></div>
<img class="bird" src="{bird}">
<div class="text"><h1>Strakaláři</h1>
<svg class="pen" width="300" height="22" viewBox="0 0 300 22"><path d="M 6 14 C 70 5 160 4 292 10" stroke="#d01f1f" stroke-width="7" fill="none" stroke-linecap="round"/>
<path d="M 40 18 C 110 13 190 13 250 16" stroke="#d01f1f" stroke-width="4" fill="none" stroke-linecap="round" opacity=".85"/></svg>
<p>{tagline}</p></div></body></html>"""


def render_play(r, page):
    sq = r.render("square", 512)
    save(sq, PLAY / "icon-512.png")  # full-bleed; Google Play rounds it
    font = find_outfit()
    if font is None:
        print("warning: Outfit font not installed, feature graphics skipped")
        return
    font64 = base64.b64encode(font.read_bytes()).decode()
    # the feature graphic uses the bird at the masters' scale: crop the central 73.44 dp of the layer
    n = round(512 / FG_SCALE)
    fg = r.render("fg", n)
    off = (n - 512) // 2
    buf = io.BytesIO()
    fg.crop((off, off, off + 512, off + 512)).save(buf, "PNG")
    bird = "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()
    page.set_viewport_size({"width": 1024, "height": 500})
    for lang, text in FEATURE_TEXT.items():
        page.set_content(feature_html(font64, bird, text))
        page.wait_for_timeout(400)
        out = PLAY / lang / "feature-graphic.png"
        out.parent.mkdir(parents=True, exist_ok=True)
        Image.open(io.BytesIO(page.screenshot())).convert("RGB").save(out)  # Play wants no alpha


def main():
    build_masters()
    with sync_playwright() as pw:
        browser = pw.chromium.launch()
        page = browser.new_page()
        r = Renderer(page)
        render_icons(r)
        render_play(r, page)
        browser.close()
    print("branding files regenerated")


if __name__ == "__main__":
    main()
